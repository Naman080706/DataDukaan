import { useEffect, useState } from "react";
import { BookOpenCheck, Database, FlaskConical, MessageSquareText } from "lucide-react";
import { api } from "./api";
import Workspace from "./components/Workspace";
import Evaluation from "./components/Evaluation";
import DataRules from "./components/DataRules";

type Page = "workspace" | "evaluation" | "rules";

const NAV: { id: Page; label: string; icon: typeof Database }[] = [
  { id: "workspace", label: "Ask your data", icon: MessageSquareText },
  { id: "evaluation", label: "Trap-suite evaluation", icon: FlaskConical },
  { id: "rules", label: "Data rules", icon: BookOpenCheck },
];

export default function App() {
  const [page, setPage] = useState<Page>("workspace");
  const [health, setHealth] = useState<{ status: string; rows?: number; llm_configured?: boolean } | null>(null);

  useEffect(() => {
    api.health().then(setHealth).catch(() => setHealth({ status: "down" }));
  }, []);

  return (
    <div className="min-h-screen">
      <header className="sticky top-0 z-20 border-b border-slate-200 bg-white/90 backdrop-blur">
        <div className="mx-auto flex max-w-7xl flex-wrap items-center gap-x-6 gap-y-2 px-4 py-3">
          <div className="flex items-center gap-2">
            <div className="grid h-8 w-8 place-items-center rounded-lg bg-brand-600 text-sm font-bold text-white">IQ</div>
            <div>
              <div className="text-base font-semibold leading-tight">RetailIQ</div>
              <div className="text-[11px] leading-tight text-slate-500">DataDukaan · ask-your-data sales agent</div>
            </div>
          </div>
          <nav className="flex flex-1 flex-wrap gap-1">
            {NAV.map(({ id, label, icon: Icon }) => (
              <button
                key={id}
                onClick={() => setPage(id)}
                className={`flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-sm font-medium transition ${
                  page === id ? "bg-brand-50 text-brand-700" : "text-slate-600 hover:bg-slate-100"
                }`}
              >
                <Icon size={16} /> {label}
              </button>
            ))}
          </nav>
          <DatasetStatus health={health} />
        </div>
      </header>
      <main className="mx-auto max-w-7xl px-4 py-6">
        {page === "workspace" && <Workspace />}
        {page === "evaluation" && <Evaluation />}
        {page === "rules" && <DataRules />}
      </main>
      <footer className="mx-auto max-w-7xl px-4 pb-8 text-xs text-slate-400">
        Data: Online Retail II, UCI Machine Learning Repository (CC BY 4.0), Dec 2009 – Dec 2011. All amounts in GBP.
        Answers are generated by an LLM from read-only SQL; always check the SQL shown.
      </footer>
    </div>
  );
}

function DatasetStatus({ health }: { health: { status: string; rows?: number; llm_configured?: boolean } | null }) {
  if (!health) return <span className="chip bg-slate-100 text-slate-500">checking…</span>;
  const ok = health.status === "ok";
  return (
    <span className={`chip ${ok ? "bg-emerald-50 text-emerald-700" : "bg-rose-50 text-rose-700"}`}>
      <Database size={12} />
      {ok ? `${health.rows?.toLocaleString()} rows · read-only` : "database unavailable"}
      {ok && !health.llm_configured && " · LLM key missing"}
    </span>
  );
}
